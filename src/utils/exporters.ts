import type { ExtractionResult, ShortClip } from '../types';
import { buildZipBlob, type ZipEntryInput } from './zipBuilder';

export function formatMmSs(totalSeconds: number): string {
  const safe = Math.max(0, Math.floor(totalSeconds));
  const hrs = Math.floor(safe / 3600);
  const mins = Math.floor((safe % 3600) / 60);
  const secs = safe % 60;
  const pad = (n: number) => String(n).padStart(2, '0');
  if (hrs > 0) {
    return `${hrs}:${pad(mins)}:${pad(secs)}`;
  }
  return `${pad(mins)}:${pad(secs)}`;
}

function formatSrtTime(seconds: number): string {
  const safe = Math.max(0, seconds);
  const hrs = Math.floor(safe / 3600);
  const mins = Math.floor((safe % 3600) / 60);
  const secs = Math.floor(safe % 60);
  const ms = Math.round((safe - Math.floor(safe)) * 1000);
  const pad2 = (n: number) => String(n).padStart(2, '0');
  const pad3 = (n: number) => String(n).padStart(3, '0');
  return `${pad2(hrs)}:${pad2(mins)}:${pad2(secs)},${pad3(ms)}`;
}

export function buildSrtContent(clip: ShortClip): string {
  if (!clip.captionSegments.length) {
    return `1\n00:00:00,000 --> ${formatSrtTime(clip.durationSeconds)}\n${clip.hookText}\n`;
  }
  return clip.captionSegments
    .map((seg, idx) => {
      const start = formatSrtTime(seg.offsetSeconds);
      const end = formatSrtTime(
        Math.min(clip.durationSeconds, seg.offsetSeconds + seg.durationSeconds)
      );
      return `${idx + 1}\n${start} --> ${end}\n${seg.text}`;
    })
    .join('\n\n');
}

function sanitizeFileSlug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 42);
}

export function buildSingleFfmpegCommand(
  canonicalUrl: string,
  clip: ShortClip
): string {
  const slug = sanitizeFileSlug(clip.title) || `short-${clip.clipNumber}`;
  const fileBase = `${String(clip.clipNumber).padStart(2, '0')}_${slug}_${clip.durationSeconds}s`;
  return [
    `# Clip ${clip.clipNumber}: ${clip.title} (${clip.startTime} - ${clip.endTime}, ${clip.durationSeconds}s)`,
    `yt-dlp -f "bv*[height<=1080]+ba/b[height<=1080]" --download-sections "*${clip.startTime}-${clip.endTime}" -o "raw_${fileBase}.%(ext)s" "${canonicalUrl}"`,
    `ffmpeg -y -i "raw_${fileBase}.mp4" -vf "crop=ih*9/16:ih,scale=1080:1920:flags=lanczos" -c:v libx264 -preset medium -crf 18 -c:a aac -b:a 192k "${fileBase}_vertical.mp4"`,
  ].join('\n');
}

export function buildBatchShellScript(
  result: ExtractionResult,
  clips: ShortClip[]
): string {
  const lines: string[] = [
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    '',
    `# Source: ${result.video.title}`,
    `# URL: ${result.video.canonicalUrl}`,
    `# Generated by ClipCut Studio (${clips.length} corporate Shorts)`,
    '',
    'mkdir -p shorts_output',
    '',
    'echo "Downloading full source video once for fast local cutting..."',
    `yt-dlp -f "bv*[height<=1080]+ba/b[height<=1080]" --merge-output-format mp4 -o "shorts_output/source.mp4" "${result.video.canonicalUrl}"`,
    '',
  ];

  for (const clip of clips) {
    const slug = sanitizeFileSlug(clip.title) || `short-${clip.clipNumber}`;
    const outName = `shorts_output/${String(clip.clipNumber).padStart(2, '0')}_${slug}_${clip.durationSeconds}s.mp4`;
    lines.push(
      `echo "Rendering Short ${clip.clipNumber}/${clips.length}: ${clip.title} (${clip.durationSeconds}s)..."`,
      `ffmpeg -y -ss ${clip.startSeconds} -i "shorts_output/source.mp4" -t ${clip.durationSeconds} -vf "crop=ih*9/16:ih,scale=1080:1920:flags=lanczos" -c:v libx264 -preset medium -crf 18 -c:a aac -b:a 192k "${outName}"`,
      ''
    );
  }

  lines.push('echo "All vertical Shorts rendered inside ./shorts_output/"');
  return lines.join('\n');
}

function escapeCsvCell(value: string): string {
  const escaped = value.replace(/"/g, '""');
  return `"${escaped}"`;
}

export function buildCsvCutSheet(result: ExtractionResult): string {
  const headers = [
    'Clip #',
    'Title',
    'Start Time',
    'End Time',
    'Duration (s)',
    'Corporate Angle',
    'Opening Hook',
    'Why It Works',
    'B-Roll Suggestion',
    'Social Caption',
    'Jump URL',
  ];

  const rows = result.clips.map((c) => [
    String(c.clipNumber),
    c.title,
    c.startTime,
    c.endTime,
    String(c.durationSeconds),
    c.corporateAngle,
    c.hookText,
    c.whyItWorks,
    c.bRollSuggestion,
    c.socialCaption,
    `https://youtu.be/${result.video.videoId}?t=${c.startSeconds}`,
  ]);

  return [headers, ...rows]
    .map((row) => row.map((cell) => escapeCsvCell(cell)).join(','))
    .join('\n');
}

export function buildMarkdownBrief(result: ExtractionResult): string {
  const lines: string[] = [
    `# ${result.video.title} — Corporate Shorts Pack`,
    '',
    `- Channel: ${result.video.channelName}`,
    `- Source URL: ${result.video.canonicalUrl}`,
    `- Total Shorts: ${result.clips.length}`,
    `- Target Duration: ~${result.targetDuration}s`,
    '',
    '---',
    '',
  ];

  for (const clip of result.clips) {
    lines.push(
      `## ${String(clip.clipNumber).padStart(2, '0')}. ${clip.title}`,
      `**Timing:** ${clip.startTime} – ${clip.endTime} (${clip.durationSeconds}s) · **Angle:** ${clip.corporateAngle}`,
      `**Hook Overlay:** ${clip.hookText}`,
      `**Rationale:** ${clip.whyItWorks}`,
      `**B-Roll / Edit Cue:** ${clip.bRollSuggestion}`,
      '',
      '**Timed Script:**',
      ...clip.captionSegments.map(
        (s) => `- [${formatMmSs(s.offsetSeconds)}] ${s.text}`
      ),
      '',
      '**Post Caption:**',
      clip.socialCaption,
      '',
      '---',
      ''
    );
  }

  return lines.join('\n');
}

export function buildBatchWindowsBatScript(
  result: ExtractionResult,
  clips: ShortClip[]
): string {
  const lines: string[] = [
    '@echo off',
    'setlocal enabledelayedexpansion',
    `REM Source: ${result.video.title}`,
    `REM URL: ${result.video.canonicalUrl}`,
    'if not exist shorts_output mkdir shorts_output',
    '',
    'echo Downloading source video once...',
    `yt-dlp -f "bv*[height<=1080]+ba/b[height<=1080]" --merge-output-format mp4 -o "shorts_output\\source.mp4" "${result.video.canonicalUrl}"`,
    '',
  ];

  for (const clip of clips) {
    const slug = sanitizeFileSlug(clip.title) || `short-${clip.clipNumber}`;
    const outName = `shorts_output\\${String(clip.clipNumber).padStart(2, '0')}_${slug}_${clip.durationSeconds}s.mp4`;
    lines.push(
      `echo Rendering Short ${clip.clipNumber}/${clips.length}...`,
      `ffmpeg -y -ss ${clip.startSeconds} -i "shorts_output\\source.mp4" -t ${clip.durationSeconds} -vf "crop=ih*9/16:ih,scale=1080:1920:flags=lanczos" -c:v libx264 -preset medium -crf 18 -c:a aac -b:a 192k "${outName}"`,
      ''
    );
  }

  lines.push('echo Done! All Shorts rendered in shorts_output\\', 'pause');
  return lines.join('\r\n');
}

export function downloadCompleteZipPack(
  result: ExtractionResult,
  selectedIds?: Set<string>
): string {
  const clips =
    selectedIds && selectedIds.size > 0
      ? result.clips.filter((c) => selectedIds.has(c.id))
      : result.clips;

  const entries: ZipEntryInput[] = [
    {
      name: '00_Production_Brief.md',
      content: buildMarkdownBrief(result),
    },
    {
      name: '00_Cut_Sheet.csv',
      content: buildCsvCutSheet(result),
    },
    {
      name: '00_Render_All_9x16.sh',
      content: buildBatchShellScript(result, clips),
    },
    {
      name: '00_Render_All_9x16.bat',
      content: buildBatchWindowsBatScript(result, clips),
    },
    {
      name: 'shorts_pack.json',
      content: JSON.stringify(result, null, 2),
    },
    ...clips.map((clip) => {
      const slug = sanitizeFileSlug(clip.title) || `short-${clip.clipNumber}`;
      return {
        name: `subtitles/${String(clip.clipNumber).padStart(2, '0')}_${slug}_${clip.durationSeconds}s.srt`,
        content: buildSrtContent(clip),
      };
    }),
  ];

  const zipBlob = buildZipBlob(entries);
  const filename = `ClipCut_${result.video.videoId}_${result.targetDuration}s_Shorts.zip`;
  const url = URL.createObjectURL(zipBlob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.rel = 'noopener';
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  window.setTimeout(() => URL.revokeObjectURL(url), 60_000);
  return filename;
}

export function triggerFileDownload(
  filename: string,
  content: string,
  mimeType = 'text/plain;charset=utf-8'
): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.rel = 'noopener';
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  window.setTimeout(() => URL.revokeObjectURL(url), 60_000);
}
